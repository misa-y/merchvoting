const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const branch = execFileSync('git', ['branch', '--show-current'], { cwd: root, encoding: 'utf8' }).trim();
if (branch !== 'utokyo-design-lab') throw new Error('Public preview must be built from utokyo-design-lab.');
const output = process.argv[2];
if (!output) throw new Error('Provide a new, empty output directory.');
const target = path.resolve(output);
fs.mkdirSync(target, { recursive: true });
if (fs.readdirSync(target).length) throw new Error('Output must be empty; refusing to overwrite files.');
const files = ['index.html', 'admin.html', 'app.js', 'admin.js', 'catalog.js', 'store.js', 'styles.css', 'preview-config.js', ...fs.readdirSync(root).filter(name => name.endsWith('.png'))];
for (const file of files) fs.copyFileSync(path.join(root, file), path.join(target, file));
const config = path.join(target, 'preview-config.js');
fs.writeFileSync(config, fs.readFileSync(config, 'utf8').replace('window.MERCH_PUBLIC_DEMO = false;', 'window.MERCH_PUBLIC_DEMO = true;'));
fs.writeFileSync(path.join(target, 'preview-provenance.json'), JSON.stringify({ repository: 'https://github.com/misa-y/merchvoting', branch, commit: execFileSync('git', ['rev-parse', 'HEAD'], {cwd:root,encoding:'utf8'}).trim(), data: 'Synthetic 30-participant scenario plus browser-local rehearsal votes. No production data.' }, null, 2));
console.log(`Built demo-only static preview: ${target}`);
